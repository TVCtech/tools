"use strict";
// Passwords arrive through stdin from the hidden Python prompt, never argv.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const cryptoEngine = require("staticrypt/lib/cryptoEngine.js");
const codec = require("staticrypt/lib/codec.js").init(cryptoEngine);
const { buildStaticryptJS } = require("staticrypt/cli/helpers.js");
const { buildTraining } = require("./build-training.cjs");
const ROOT = path.resolve(__dirname, "..");
const ROLES = ["technician", "admin"];
const DEFAULT_ACCOUNTS = [
    { id: "technician", label: "Technician", role: "technician" },
    { id: "admin", label: "Admin", role: "admin" },
];

function inside(parent, child) {
    const relative = path.relative(parent, child);
    return relative === "" || (!relative.startsWith(".." + path.sep) && relative !== ".." && !path.isAbsolute(relative));
}

function loadTools(source) {
    source = fs.realpathSync(source);
    if (inside(fs.realpathSync(ROOT), source)) throw new Error("Private source must be outside the public repository.");
    const manifest = JSON.parse(fs.readFileSync(path.join(source, "manifest.json"), "utf8"));
    if (!Array.isArray(manifest.tools)) throw new Error("manifest.json needs a tools list.");
    const ids = new Set();
    return manifest.tools.map((tool) => {
        if (!tool || !/^[a-z0-9][a-z0-9-]*$/.test(tool.id) || ids.has(tool.id)) throw new Error("Each tool needs a unique lowercase id.");
        ids.add(tool.id);
        if (!ROLES.includes(tool.access) || typeof tool.title !== "string" || !tool.title.trim()) throw new Error("Each tool needs a title and technician/admin access.");
        if (typeof tool.file !== "string" || !tool.file.endsWith(".html")) throw new Error("Each tool must name a self-contained HTML file.");
        const file = fs.realpathSync(path.resolve(source, tool.file));
        if (!inside(source, file)) throw new Error("Tool source cannot leave the private source folder.");
        return { id: tool.id, title: tool.title, access: tool.access, html: fs.readFileSync(file, "utf8") };
    });
}

function escapeHtml(value) {
    return value.replaceAll("&", "&amp;").replaceAll('"', "&quot;")
        .replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}

function accountList(output, savedAccounts) {
    const filename = path.join(output, "staff-accounts.json");
    if (!fs.existsSync(filename) && !savedAccounts && fs.existsSync(path.join(output, "staff-account-settings.json"))) throw new Error("Existing company keys are needed to preserve company access.");
    if (!fs.existsSync(filename) && !savedAccounts) return DEFAULT_ACCOUNTS.map(account => ({ ...account }));
    const record = fs.existsSync(filename) ? JSON.parse(fs.readFileSync(filename, "utf8")) : {version: 1, accounts: savedAccounts};
    if (record.version !== 1 || !Array.isArray(record.accounts)) throw new Error("Unsupported account list.");
    const ids = new Set();
    for (const account of record.accounts) {
        if (!validAccount(account) || ids.has(account.id)) throw new Error("Invalid account list.");
        ids.add(account.id);
    }
    for (const required of DEFAULT_ACCOUNTS) {
        const account = record.accounts.find(entry => entry.id === required.id);
        if (!account || account.role !== required.role || account.label !== required.label) throw new Error("Existing roles must remain available.");
    }
    return record.accounts;
}

function validAccount(account) {
    if (!account || typeof account.id !== "string" || !/^[a-z][a-z0-9-]{1,39}$/.test(account.id) ||
        ["users", "staff", "index"].includes(account.id) ||
        typeof account.label !== "string" || !account.label.trim() || account.label.length > 80) return false;
    // Companies inherit Technician access; the existing Admin is the only Admin account.
    return account.role === (account.id === "admin" ? "admin" : "technician");
}

function page(role, encrypted, account = DEFAULT_ACCOUNTS.find(entry => entry.id === role), {blankAccount = false} = {}) {
    return fs.readFileSync(path.join(__dirname, "staff-page.html"), "utf8")
        .replaceAll("@@TITLE@@", escapeHtml(account.label))
        .replace("@@ACCOUNT@@", blankAccount ? "" : account.id)
        .replace("@@CONFIG@@", JSON.stringify({ role, account: account.id, accountLabel: account.label, encrypted }).replaceAll("<", "\\u003c"));
}

function assets() {
    return {
        "assets/staticrypt.js": "/*! StatiCrypt 3.5.4, MIT. See staticrypt.LICENSE.txt. Generated by scripts/build-staff.cjs. */\nwindow.staticryptInitiator = " + buildStaticryptJS() + ";\n",
        "assets/staticrypt.LICENSE.txt": fs.readFileSync(path.join(ROOT, "node_modules/staticrypt/LICENSE"), "utf8"),
    };
}

function saveFiles(output, files) {
    // Finish encryption of every account before touching any published file.
    for (const [name, content] of Object.entries(files)) {
        const target = path.join(output, name);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        const temp = target + ".tmp";
        try {
            fs.writeFileSync(temp, content, "utf8");
            fs.renameSync(temp, target);
        } finally {
            if (fs.existsSync(temp)) fs.unlinkSync(temp);
        }
    }
}

function privateKeyPath(filename, output) {
    const target = path.resolve(filename);
    let ancestor = path.dirname(target);
    while (!fs.existsSync(ancestor)) ancestor = path.dirname(ancestor);
    const resolved = path.resolve(fs.realpathSync(ancestor), path.relative(ancestor, target));
    if (inside(fs.realpathSync(ROOT), resolved) || inside(path.resolve(output), resolved)) {
        throw new Error("Encryption keys must stay outside the public repository and output.");
    }
    if (fs.existsSync(target) && fs.lstatSync(target).isSymbolicLink()) throw new Error("Key file must not be a symlink.");
    return target;
}

function saveKeys(filename, record) {
    const directory = path.dirname(filename);
    fs.mkdirSync(directory, { recursive: true, mode: 0o700 });
    // Only the dedicated key directory is accepted by the wrapper by default.
    const temp = filename + "." + crypto.randomBytes(8).toString("hex") + ".tmp";
    try {
        fs.writeFileSync(temp, JSON.stringify(record) + "\n", { encoding: "utf8", mode: 0o600, flag: "wx" });
        fs.renameSync(temp, filename);
    } finally {
        if (fs.existsSync(temp)) fs.unlinkSync(temp);
    }
}

async function build({ source, passwords, keyFile, output = ROOT, companyAccounts = [], trainingSource, trainingConfiguration }) {
    if (passwords) {
        if (ROLES.some((role) => typeof passwords[role] !== "string" || !passwords[role])) throw new Error("Both passwords are required.");
        if (passwords.admin === passwords.technician) throw new Error("Use different passwords for Admin and Technician.");
    } else if (!keyFile) throw new Error("Passwords or a private key file are required.");
    const keyPath = keyFile ? privateKeyPath(keyFile, output) : null;
    let savedKeys = null;
    if (keyPath && fs.existsSync(keyPath)) {
        if (process.platform !== "win32" && (fs.statSync(keyPath).mode & 0o077)) throw new Error("Key file must be readable only by its owner.");
        savedKeys = JSON.parse(fs.readFileSync(keyPath, "utf8"));
    }
    const originalKeys = JSON.stringify(savedKeys);
    const tools = loadTools(source);
    const existingAccounts = accountList(output, savedKeys?.accountMetadata);
    const accounts = existingAccounts.map(account => ({ ...account }));
    const newPasswords = new Set();
    for (const account of companyAccounts) {
        if (!validAccount({ ...account, role: "technician" }) || ROLES.includes(account.id) ||
            typeof account.password !== "string" || account.password.length < 16 || newPasswords.has(account.password)) {
            throw new Error("Company accounts need valid unique names and different passwords of at least 16 characters.");
        }
        if (accounts.some(existing => existing.id === account.id)) throw new Error("Account already exists; creating an account must not change its password.");
        if (fs.existsSync(path.join(output, account.id + ".html"))) throw new Error("New account page would replace an existing file.");
        newPasswords.add(account.password);
        accounts.push({ id: account.id, label: account.label, role: "technician" });
    }
    if (companyAccounts.length && !keyPath) throw new Error("Company accounts require a private key file for future rebuilds.");
    const saltPath = path.join(output, "staff-salts.json");
    const salts = fs.existsSync(saltPath) ? JSON.parse(fs.readFileSync(saltPath, "utf8")) : {};
    for (const account of accounts) {
        salts[account.id] ??= crypto.randomBytes(16).toString("hex");
        if (!/^[a-f0-9]{32}$/.test(salts[account.id])) throw new Error("Invalid staff salt configuration.");
    }
    let keys;
    const existingData = new Map();
    const existingCompanies = existingAccounts.filter(account => !ROLES.includes(account.id));
    if (!passwords || existingCompanies.length) {
        if (!keyPath) throw new Error("Existing company keys are needed to preserve company access.");
        if (process.platform !== "win32" && (fs.statSync(keyPath).mode & 0o077)) throw new Error("Key file must be readable only by its owner.");
        keys = savedKeys;
        if (keys.version !== 1) throw new Error("Unsupported key file.");
        const verifyAccounts = passwords ? existingCompanies : existingAccounts;
        for (const account of verifyAccounts) {
            const key = ROLES.includes(account.id) ? keys.roles?.[account.id] : keys.accounts?.[account.id];
            if (!key || key.salt !== salts[account.id] || !/^[a-f0-9]{64}$/.test(key.hash)) throw new Error("Saved keys do not match the site configuration.");
            const existing = fs.readFileSync(path.join(output, account.id + ".html"), "utf8");
            const config = JSON.parse(existing.match(/<script id="staff-config" type="application\/json">(.*?)<\/script>/s)[1]);
            const checked = await codec.decode(config.encrypted.staticryptEncryptedMsgUniqueVariableName, key.hash, key.salt);
            if (!checked.success) throw new Error("Saved keys no longer unlock this site. Refresh the affected private keys before rebuilding.");
            const data = JSON.parse(checked.decoded);
            if (data.role !== account.role || (data.account || data.role) !== account.id) throw new Error("Saved keys do not match the account.");
            existingData.set(account.id, data);
        }
    }
    if (passwords) {
        keys ??= { version: 1, roles: {} };
        for (const role of ROLES) keys.roles[role] = {
            salt: salts[role], hash: await cryptoEngine.hashPassword(passwords[role], salts[role]),
        };
    }
    if (companyAccounts.length) keys.accounts ??= {};
    for (const account of companyAccounts) {
        keys.accounts[account.id] = {
            salt: salts[account.id], hash: await cryptoEngine.hashPassword(account.password, salts[account.id]),
        };
    }
    keys.accountMetadata = accounts;
    const files = assets();
    if (accounts.some(account => !ROLES.includes(account.id))) files["staff-account-settings.json"] = JSON.stringify({version: 1, privateAccountIndex: true}) + "\n";
    const training = trainingSource ? buildTraining({source: trainingSource, output, keys, configuration: trainingConfiguration}) : null;
    if (training) {
        Object.assign(files, training.files);
        files["assets/training-host.js"] = fs.readFileSync(path.join(ROOT, "assets/training-host.js"), "utf8");
        files["assets/training-viewer.js"] = fs.readFileSync(path.join(ROOT, "assets/training-viewer.js"), "utf8");
    }
    for (const account of accounts) {
        const selected = tools.filter((tool) => account.role === "admin" || tool.access === "technician");
        const packageInfo = training ? training.forAccount(account) : existingData.get(account.id)?.training;
        const plain = JSON.stringify({ version: 1, role: account.role, account: account.id, tools: selected, ...(packageInfo ? {training: packageInfo} : {}) });
        const key = ROLES.includes(account.id) ? keys.roles[account.id] : keys.accounts[account.id];
        const encrypted = await codec.encodeWithHashedPassword(plain, key.hash);
        const pageConfiguration = {
            staticryptEncryptedMsgUniqueVariableName: encrypted,
            staticryptSaltUniqueVariableName: salts[account.id],
            isRememberEnabled: false,
            rememberDurationInDays: 0,
        };
        files[account.id + ".html"] = page(account.role, pageConfiguration, account);
        if (account.id === "technician") files["users.html"] = page(account.role, pageConfiguration, account, {blankAccount: true});
    }
    files["staff-salts.json"] = JSON.stringify(salts, null, 2) + "\n";
    saveFiles(output, files);
    if (keyPath && JSON.stringify(keys) !== originalKeys) saveKeys(keyPath, keys);
    if (fs.existsSync(path.join(output, "staff-accounts.json"))) fs.unlinkSync(path.join(output, "staff-accounts.json"));
}

async function main() {
    if (process.argv[2] === "--prepare") {
        if (ROLES.some((role) => fs.existsSync(path.join(ROOT, role + ".html")))) throw new Error("Role pages already exist; preparation will not overwrite them.");
        saveFiles(ROOT, { ...assets(), "users.html": page("technician", null, undefined, {blankAccount: true}), ...Object.fromEntries(ROLES.map((role) => [role + ".html", page(role, null)])) });
        return;
    }
    const input = JSON.parse(fs.readFileSync(0, "utf8"));
    await build(input);
    console.log("Encrypted user pages built. No passwords are included in the site output.");
    if (input.passwords && input.keyFile) console.log("Private encryption keys saved for future rebuilds.");
}

module.exports = { build, loadTools, page };
if (require.main === module) main().catch(() => {
    // Do not print inputs or a child-process command containing credentials.
    console.error("Build failed. Check the private manifest, installed dependencies and private key file. If keys are missing or outdated, run set_staff_passwords.py again. Check generated pages before publishing.");
    process.exitCode = 1;
});
